class MainMarkdown(HTMLParser):
    """Markdown for the <main> element. Skips controls, visually hidden text and elements marked
    data-export="skip". Margin labels (.side) become "**Label:**"; paper entries become list items
    with one line per part."""

    VOID = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}
    BLOCK = {"p", "div", "section", "article", "header", "footer", "ul", "ol", "dl", "details", "summary",
             "table", "figure", "figcaption", "blockquote", "aside", "nav", "address", "caption"}
    LINE_CLASSES = {"au", "ve", "aw", "nt", "ds", "ln", "desc", "topics", "meta"}
    SKIP_CLASSES = {"sr", "skip", "visually-hidden", "sr-only"}

    def __init__(self, url, root="main"):
        super().__init__(convert_charrefs=True)
        self.url = url
        self.root = root      # "main", or "body" for a page that has no <main> yet
        self.in_main = False
        self.skip = 0
        self.out = []
        self.stack = []       # closing actions for open elements inside <main>
        self.hrefs = []
        self.li = 0           # depth of open list items
        self.dl = 0
        self.cell = 0
        self.fresh = True     # nothing written since the last break, list marker or label

    # helpers
    def emit(self, text):
        self.out.append(text)

    def brk(self):
        """Paragraph break; inside a list item, a continuation line."""
        if self.fresh:
            return
        if self.cell:
            self.emit(" ")
        elif self.li:
            self.emit("\n" + "  " * self.li)
        else:
            self.emit("\n\n")
        self.fresh = True

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == self.root:
            self.in_main = True
            return
        if not self.in_main:
            return
        if self.skip:
            self.skip += tag not in self.VOID
            return
        classes = set((a.get("class") or "").split())
        if (tag in {"script", "style", "svg", "button", "template", "noscript", "input", "select", "textarea"}
                or "hidden" in a or a.get("aria-hidden") == "true" or a.get("data-export") == "skip"
                or classes & self.SKIP_CLASSES):
            self.skip = int(tag not in self.VOID)
            return
        action = ""
        if tag == "li":
            self.emit("\n" + "  " * self.li + "- ")
            self.li += 1
            self.fresh = True
            action = "li"
        elif tag in {"ul", "ol"}:
            if self.li:
                self.fresh = True
            else:
                self.emit("\n\n")
                self.fresh = True
            action = "list"
        elif tag == "dl":
            self.brk()
            self.dl += 1
            action = "dl"
        elif tag == "dt":
            self.emit("\n" + "  " * self.li + "- **")
            self.fresh = True
            action = "label"
        elif tag == "dd" or (tag == "div" and self.dl and not self.li):
            action = ""
        elif "side" in classes:
            self.brk()
            self.emit("**")
            action = "label"
        elif re.fullmatch(r"h[1-6]", tag):
            if self.li:
                self.brk()
                self.emit("**")
                action = "bold"
            else:
                self.emit("\n\n" + "#" * int(tag[1]) + " ")
                self.fresh = True
                action = "heading"
        elif tag == "tr":
            self.emit("\n- ")
            self.cell = 0
            self.fresh = True
        elif tag in {"td", "th"}:
            if self.cell:
                self.emit(" | ")
            self.cell += 1
            self.fresh = True
            action = "cell"
        elif tag in self.BLOCK or (tag == "span" and classes & self.LINE_CLASSES) or (tag == "cite" and self.li):
            self.brk()
            if tag == "cite":
                self.emit("**")
                action = "bold"
            else:
                action = "block"
        elif tag == "br":
            if self.cell:
                self.emit(" ")
            else:
                self.emit("\n" + "  " * self.li)
                self.fresh = True
        elif tag in {"strong", "b", "cite"}:
            self.emit("**")
            action = "bold"
        elif tag in {"em", "i"}:
            self.emit("*")
            action = "italic"
        elif tag == "a":
            href = a.get("href", "")
            self.hrefs.append(urljoin(self.url, href) if href else "")
            self.emit("[")
            action = "link"
        elif tag == "img" and a.get("alt"):
            self.emit("[Image: " + a["alt"] + "]")
            self.fresh = False
        if tag not in self.VOID:
            self.stack.append(action)

    def handle_endtag(self, tag):
        if tag == self.root:
            self.in_main = False
            return
        if not self.in_main:
            return
        if self.skip:
            self.skip -= 1
            return
        if tag in self.VOID or not self.stack:
            return
        action = self.stack.pop()
        if tag == "table":
            self.cell = 0       # the rows are over: blocks after the table get paragraph breaks again
        if action == "li":
            self.li -= 1
        elif action == "list":
            if not self.li:
                self.emit("\n\n")
                self.fresh = True
        elif action == "dl":
            self.dl -= 1
            self.emit("\n\n")
            self.fresh = True
        elif action == "label":
            self.emit("** " if self.out and self.out[-1].rstrip().endswith(":") else ":** ")
            self.fresh = True
        elif action == "heading":
            self.emit("\n\n")
            self.fresh = True
        elif action == "bold":
            self.emit("**")
        elif action == "italic":
            self.emit("*")
        elif action == "cell":
            pass
        elif action == "link":
            href = self.hrefs.pop() if self.hrefs else ""
            self.emit("](" + href.replace(" ", "%20").replace("(", "%28").replace(")", "%29") + ")" if href else "]")
        elif action == "block" and not self.li and not self.cell:
            self.emit("\n\n")
            self.fresh = True

    def handle_data(self, data):
        if not self.in_main or self.skip:
            return
        text = re.sub(r"\s+", " ", data).replace("‑", "-").replace("*", "\\*")
        if text.strip():
            if self.fresh:
                text = text.lstrip()
            self.fresh = False
            self.emit(text)
        elif not self.fresh:
            self.emit(" ")

    def markdown(self):
        text = "".join(self.out)
        text = text.replace("****", "")                              # empty bold
        text = re.sub(r"\[ +", "[", text)
        text = re.sub(r" +\]\(", "](", text)
        lines = []
        for line in text.split("\n"):
            indent = len(line) - len(line.lstrip(" "))
            body = re.sub(r" {2,}", " ", line.strip())
            lines.append((" " * indent + body) if body else "")
        body = re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip()
        return f"Canonical page: {self.url}\n\n{body}\n"


def canonical(name):
    return BASE if name == "index.html" else BASE + name


def export_text(pages_html):
    chunks = [HEADER]
    for name in PAGES:
        if name not in pages_html:
            continue
        text = pages_html[name]
        parser = MainMarkdown(canonical(name), "main" if re.search(r"<main[\s>]", text) else "body")
        parser.feed(text)
        parser.close()
        chunks.append(parser.markdown())
    return "\n---\n\n".join(chunks)


