class PageRefs(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.ids, self.dup_ids, self.refs, self.meta, self.links, self.jsonld = set(), set(), [], {}, {}, []
        self.title, self.in_title, self._ld = "", False, None
        self.pub_ids = []
        self._depth_pubs = 0

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if a.get("id"):
            (self.dup_ids if a["id"] in self.ids else self.ids).add(a["id"])
        if tag == "a" and a.get("name"):
            self.ids.add(a["name"])
        if tag == "title":
            self.in_title = True
        if tag == "meta":
            key = a.get("name") or a.get("property")
            if key:
                self.meta.setdefault(key, a.get("content", ""))
            if key == "og:image" and a.get("content"):
                self.refs.append(a["content"])
        if tag == "link" and a.get("rel"):
            for r in a["rel"].split():
                self.links.setdefault(r.lower(), []).append(a.get("href", ""))
            if set(a["rel"].lower().split()) & {"stylesheet", "icon", "apple-touch-icon", "alternate"} and a.get("href"):
                self.refs.append(a["href"])
        elif tag != "link" and a.get("href"):
            self.refs.append(a["href"])
        if a.get("src"):
            self.refs.append(a["src"])
        if tag == "script" and a.get("type") == "application/ld+json":
            self._ld = []
        if tag == "ol" and "pubs" in (a.get("class") or "").split():
            self._depth_pubs += 1
        elif tag == "li" and self._depth_pubs and a.get("id"):
            self.pub_ids.append(a["id"])

    def handle_endtag(self, tag):
        if tag == "title":
            self.in_title = False
        if tag == "script" and self._ld is not None:
            self.jsonld.append("".join(self._ld))
            self._ld = None
        if tag == "ol" and self._depth_pubs:
            self._depth_pubs -= 1

    def handle_data(self, data):
        if self._ld is not None:
            self._ld.append(data)
        if self.in_title:
            self.title += data


def local_target(href, page):
    """Map a link to this site, relative or absolute (https://mengyuan-l.github.io/…), to (path relative to
    the site root, fragment); None for other sites and schemes."""
    if href.startswith(BASE):
        parts = urlsplit(href[len(BASE):])
        path = unquote(parts.path)
        if path == "" or path.endswith("/"):
            path += "index.html"
        return path, parts.fragment
    parts = urlsplit(href)
    if parts.scheme or parts.netloc:
        return None
    if not parts.path:
        return page, parts.fragment
    path = unquote(urlsplit(urljoin("https://site.invalid/" + page, parts.path)).path).lstrip("/")
    if path == "" or path.endswith("/"):
        path += "index.html"
    return path, parts.fragment


def collapse(text):
    """Runs of ASCII whitespace become one space; a no-break space stays."""
    return re.sub(r"[ \t\n\r\f]+", " ", text).strip()


def start_tag(tag, attrs):
    return "<" + tag + "".join(f' {k}="{v}"' for k, v in sorted(attrs, key=lambda kv: kv[0])) + ">"


class Canon(HTMLParser):
    """An HTML fragment in canonical form: character references decoded, ASCII whitespace collapsed and
    attributes sorted, so the same markup compares equal however its entities and spaces were written."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.out = []

    def handle_starttag(self, tag, attrs):
        self.out.append(start_tag(tag, attrs))

    def handle_endtag(self, tag):
        self.out.append(f"</{tag}>")

    def handle_data(self, data):
        self.out.append(data)


def canon(fragment):
    parser = Canon()
    parser.feed(fragment)
    parser.close()
    return collapse("".join(parser.out))


class PaperEntries(HTMLParser):
    """The paper entries of a page (ol.pubs > li[id]): for each, the text and link of its <cite> and the
    canonical form (see canon()) of the parts that come from the data: .au, .ve, .ds, .nt, .ln."""

    PARTS = {"au", "ve", "ds", "nt", "ln"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.entries = OrderedDict()
        self.ols = []          # for each open <ol> outside an entry: is it an ol.pubs?
        self.entry = None      # the open entry
        self.depth = 0         # element depth inside the open entry; its <li> is 1
        self.part = None       # [class, depth, pieces] of the open part
        self.cite = None       # depth of the open <cite>

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if self.entry is None:
            if tag == "ol":
                self.ols.append("pubs" in (a.get("class") or "").split())
            elif tag == "li" and a.get("id") and self.ols and self.ols[-1]:
                self.entry = self.entries[a["id"]] = {"cite_text": None, "cite_href": None, "parts": {}}
                self.depth = 1
            return
        if tag not in MainMarkdown.VOID:
            self.depth += 1
        if self.part is not None:
            self.part[2].append(start_tag(tag, attrs))
        elif self.cite is not None:
            if tag == "a" and self.entry["cite_href"] is None:
                self.entry["cite_href"] = a.get("href", "")
        elif self.depth == 2 and tag == "cite":
            self.cite, self.entry["cite_text"] = 2, ""
        elif self.depth == 2:
            names = [c for c in (a.get("class") or "").split() if c in self.PARTS]
            if names:
                self.part = [names[0], 2, []]

    def handle_endtag(self, tag):
        if self.entry is None:
            if tag == "ol" and self.ols:
                self.ols.pop()
            return
        if tag in MainMarkdown.VOID:
            return
        if self.part is not None:
            if self.depth == self.part[1]:
                self.entry["parts"].setdefault(self.part[0], []).append(collapse("".join(self.part[2])))
                self.part = None
            else:
                self.part[2].append(f"</{tag}>")
        elif self.cite is not None and self.depth == self.cite:
            self.cite = None
        self.depth -= 1
        if self.depth == 0:
            self.entry = None

    def handle_data(self, data):
        if self.part is not None:
            self.part[2].append(data)
        elif self.cite is not None:
            self.entry["cite_text"] += data


def difference(page, data):
    """How a part on a page differs from the generated one, in a few words for a check message."""
    if page is None:
        return "missing on the page"
    if data is None:
        return "the record has none"
    plain = lambda s: re.sub(r"<[^>]+>", "", s).replace("\xa0", " ")
    hrefs = lambda s: re.findall(r'href="([^"]*)"', s)
    if plain(page) != plain(data):
        return f'page "{plain(page)}", data "{plain(data)}"'
    if hrefs(page) != hrefs(data):
        return f"page links {hrefs(page)}, data links {hrefs(data)}"
    return f"page {page}, data {data}"


def entry_problems(where, entry, pub):
    """Differences between a hand-copied paper entry on a topic page (see PaperEntries) and its record.
    The margin tag, the award line and the one-sentence summary are the page's own and are not compared."""
    if pub is None:
        return [f"{where}: no record with this id in _data/publications.json"]
    problems = []
    title = canon(esc(pub["title"]))
    if entry["cite_text"] is None:
        problems.append(f"{where}: no <cite> title")
    elif collapse(entry["cite_text"]) != title:
        problems.append(f"{where}: title differs from the data ({difference(collapse(entry['cite_text']), title)})")
    targets = (["https://doi.org/" + pub["doi"]] if pub.get("doi") else []) + [l["url"] for l in pub.get("links") or []]
    if entry["cite_href"] is not None and entry["cite_href"] not in targets:
        problems.append(f"{where}: the title links to {entry['cite_href']}, which is neither the record's DOI nor one of its links")
    disclosures = disclosures_html(pub)
    for part, what, generated in (("au", "authors differ", authors_html(pub)),
                                  ("ve", "venue differs", f"<i>{venue_html(pub['venue'])}</i>"),   # without the acceptance rate
                                  ("ds", "disclosures differ", disclosures),
                                  ("ln", "link row differs", link_row(pub))):
        page = (entry["parts"].get(part) or [None])[0]
        data = canon(generated) if generated else None
        if page != data:
            problems.append(f"{where}: {what} from the data ({difference(page, data)})")
    notes = [canon(n) for n in notes_html(pub)]
    for page in entry["parts"].get("nt") or []:   # a page may leave a note out, but not change it
        if page not in notes:
            problems.append(f"{where}: note differs from the data ({difference(page, notes[0] if notes else None)})")
    return problems


def jsonld_links(value):
    """(key, url) for every "@id", "url", "item" or "image" in a JSON-LD value that points to this site."""
    if isinstance(value, dict):
        for key, v in value.items():
            if key in ("@id", "url", "item", "image") and isinstance(v, str):
                if v.startswith(BASE):
                    yield key, v
            else:
                yield from jsonld_links(v)
    elif isinstance(value, list):
        for v in value:
            yield from jsonld_links(v)


def site_problems(pages_html, data):
    problems = []
    parsed = {}
    for name, text in pages_html.items():
        refs = PageRefs()
        refs.feed(text)
        parsed[name] = refs

    def link_problem(href, page):
        """Why a link from `page` to this site points to nothing, or None (also None for other sites)."""
        target = local_target(href, page)
        if target is None:
            return None
        path, fragment = target
        if not (ROOT / path).exists():
            return f"broken local link {href}"
        if fragment and path.endswith(".html"):
            ids = parsed[path].ids if path in parsed else set()
            if fragment not in ids and fragment != "top":
                return f"missing anchor {href}"
        return None
    for name, refs in sorted(parsed.items()):
        for dup in sorted(refs.dup_ids):
            problems.append(f"{name}: duplicate id \"{dup}\"")
        for block in refs.jsonld:
            try:
                json.loads(block.replace("<\\/", "</"))
            except ValueError as e:
                problems.append(f"{name}: JSON-LD does not parse ({e})")
        if name in PAGES:
            if not refs.title.strip():
                problems.append(f"{name}: missing <title>")
            for key in ("description", "og:title", "og:description", "og:type", "og:url", "og:image"):
                if not refs.meta.get(key):
                    problems.append(f"{name}: missing meta {key}")
            if canonical(name) not in refs.links.get("canonical", []):
                problems.append(f"{name}: canonical link should be {canonical(name)}")
            if refs.meta.get("og:url") and refs.meta["og:url"] != canonical(name):
                problems.append(f"{name}: og:url should be {canonical(name)}")
        for href in refs.refs:
            problem = link_problem(href, name)
            if problem:
                problems.append(f"{name}: {problem}")
    # JSON-LD links to this site ("url", "item", "image", "@id") must point to an existing file and #anchor.
    # An "@id" may instead name a node at the top level of that page's JSON-LD graph, such as #person.
    graphs, nodes = {}, {}
    for name, refs in parsed.items():
        graphs[name], nodes[name] = [], set()
        for block in refs.jsonld:
            try:
                ld = json.loads(block.replace("<\\/", "</"))
            except ValueError:
                continue   # already reported above
            graphs[name].append(ld)
            for node in (ld.get("@graph", [ld]) if isinstance(ld, dict) else ld):
                if isinstance(node, dict) and isinstance(node.get("@id"), str):
                    nodes[name].add(node["@id"])
    for name in sorted(graphs):
        for ld in graphs[name]:
            for key, url in jsonld_links(ld):
                problem = link_problem(url, name)
                path = local_target(url, name)[0]
                if problem and not (key == "@id" and url in nodes.get(path, ())):
                    problems.append(f"{name}: JSON-LD {key}: {problem}")
    # Paper entries on the topic pages repeat records of _data/publications.json by hand; each must still match.
    by_id = {p["id"]: p for p in data["publications"]}
    for name, text in sorted(pages_html.items()):
        if name == "index.html":
            continue
        entries = PaperEntries()
        entries.feed(text)
        for pid, entry in entries.entries.items():
            problems += entry_problems(f"{name} #{pid}", entry, by_id.get(pid))
    # llms.txt: its Markdown links to this site must point to an existing file and #anchor
    llms = ROOT / "llms.txt"
    if llms.exists():
        for url in re.findall(r"\]\(([^)\s]+)\)", llms.read_text(encoding="utf-8")):
            problem = link_problem(url, "llms.txt")
            if problem:
                problems.append(f"llms.txt: {problem}")
    # Publication ids: data, the generated list on index.html, and the JSON-LD nodes must agree.
    data_ids = [p["id"] for p in data["publications"]]
    if len(set(data_ids)) != len(data_ids):
        problems.append("_data/publications.json: duplicate publication ids")
    html_ids = parsed["index.html"].pub_ids if "index.html" in parsed else []
    if set(html_ids) != set(data_ids):
        missing, extra = sorted(set(data_ids) - set(html_ids)), sorted(set(html_ids) - set(data_ids))
        problems.append(f"index.html: publication ids differ from the data (missing {missing}, extra {extra})")
    ld_ids, ld_ok = set(), True
    for block in parsed["index.html"].jsonld if "index.html" in parsed else []:
        try:
            for node in json.loads(block.replace("<\\/", "</")).get("@graph", []):
                if node.get("@type") in {"ScholarlyArticle", "Thesis"}:
                    ld_ids.add(node.get("@id", "").replace(BASE + "#", ""))
        except (ValueError, AttributeError):
            ld_ok = False   # already reported above
    if ld_ok and ld_ids != set(data_ids):
        problems.append(f"index.html: JSON-LD publication ids differ from the data "
                        f"(missing {sorted(set(data_ids) - ld_ids)}, extra {sorted(ld_ids - set(data_ids))})")
    if "index.html" in pages_html and pages_html["index.html"].count(WEB_STAT) != 1:
        problems.append("index.html: the Web-Stat counter snippet is missing or was changed")
    # sitemap.xml lists every public page, and nothing that does not exist or should not be indexed
    # (404.html is noindex; the sept_lab.html redirect stub has its canonical link on septlab.com)
    try:
        ns = {"s": "http://www.sitemaps.org/schemas/sitemap/0.9"}
        locs = [e.text.strip() for e in ElementTree.parse(SITEMAP).getroot().findall("s:url/s:loc", ns) if e.text]
        for name in PAGES:
            if canonical(name) not in locs:
                problems.append(f"sitemap.xml: missing {canonical(name)}")
        for loc in locs:
            if loc.startswith(BASE):
                path = loc[len(BASE):] or "index.html"
                if not (ROOT / path).exists():
                    problems.append(f"sitemap.xml: {loc} does not exist")
                elif path in parsed:
                    if "noindex" in parsed[path].meta.get("robots", "").lower():
                        problems.append(f"sitemap.xml: {loc} is marked noindex; remove it from the sitemap")
                    elif loc not in parsed[path].links.get("canonical", [loc]):
                        problems.append(f"sitemap.xml: {loc} has its canonical link elsewhere; remove it from the sitemap")
    except (OSError, ElementTree.ParseError) as e:
        problems.append(f"sitemap.xml: {e}")
    # Jekyll turns root-level Markdown files into pages
    for md in sorted(ROOT.glob("*.md")):
        problems.append(f"{md.name}: Markdown at the site root would be published as a page by Jekyll; move it under _tools/ or another _folder")
    return problems


