def page_title(text):
    m = re.search(r"<title>(.*?)</title>", text, re.S)
    return html.unescape(m.group(1).strip()) if m else ""


def homepage_lastmod():
    """dateModified for the profile page: profile.json "date_modified", else the homepage <lastmod> in sitemap.xml."""
    try:
        ns = {"s": "http://www.sitemaps.org/schemas/sitemap/0.9"}
        for url in ElementTree.parse(SITEMAP).getroot().findall("s:url", ns):
            if (url.findtext("s:loc", "", ns) or "").strip() == BASE:
                return (url.findtext("s:lastmod", "", ns) or "").strip() or None
    except (OSError, ElementTree.ParseError):
        return None
    return None


def jsonld(profile, pubs, title):
    person_id = BASE + "#person"
    usc_id = BASE + "#usc"
    lab = profile["lab"]
    me = profile["person"]
    dept_ids = [BASE + "#" + d["id"] for d in profile["departments"]]
    loc = me.get("work_location") or {}

    page = {"@type": "ProfilePage", "@id": BASE + "#profilepage", "url": BASE, "name": title, "inLanguage": "en"}
    modified = profile.get("date_modified") or homepage_lastmod()
    if modified:
        page["dateModified"] = modified
    page.update({"mainEntity": {"@id": person_id}, "isPartOf": {"@id": BASE + "#website"},
                 "relatedLink": [lab["url"]] + [s["url"] for s in profile.get("related_sites") or []]})
    graph = [
        page,
        {"@type": "WebSite", "@id": BASE + "#website", "url": BASE, "name": me["display_name"], "inLanguage": "en",
         "publisher": {"@id": person_id}},
    ]
    person = {
        "@type": "Person", "@id": person_id, "name": me["name"], "alternateName": me["alternate_names"],
        "givenName": me["given_name"], "familyName": me["family_name"], "url": BASE,
        "image": urljoin(BASE, me["image"]), "email": "mailto:" + me["email"], "jobTitle": me["job_title"],
        "description": me["description"], "worksFor": {"@id": usc_id},
        "affiliation": [{"@id": i} for i in dept_ids] + [{"@id": lab["id"]}], "memberOf": {"@id": lab["id"]},
        "alumniOf": [{"@type": "CollegeOrUniversity", "name": a["name"], "url": a["url"]} for a in me["alumni_of"]],
        "knowsAbout": me["knows_about"], "award": me["awards"], "sameAs": me["same_as"],
    }
    if loc:
        person["workLocation"] = {
            "@type": "Place", "name": loc["name"],
            "address": {"@type": "PostalAddress", "streetAddress": loc["street"], "addressLocality": loc["locality"],
                        "addressRegion": loc["region"], "postalCode": loc["postal_code"],
                        "addressCountry": loc["country"]}}
    graph.append(person)
    graph.append({"@type": "CollegeOrUniversity", "@id": usc_id, "name": profile["university"]["name"],
                  "url": profile["university"]["url"]})
    for dept, dept_id in zip(profile["departments"], dept_ids):
        graph.append({"@type": "Organization", "@id": dept_id, "name": dept["name"], "url": dept["url"],
                      "parentOrganization": {"@id": usc_id}})
    lab_node = {"@type": "Organization", "@id": lab["id"], "name": lab["name"], "alternateName": lab["alternate_name"],
                "url": lab["url"], "founder": {"@id": person_id}, "parentOrganization": {"@id": dept_ids[0]}}
    if lab.get("same_as"):
        lab_node["sameAs"] = lab["same_as"]
    graph.append(lab_node)
    for site in profile.get("related_sites") or []:
        graph.append({"@type": "WebSite", "@id": site["id"], "name": site["name"], "url": site["url"],
                      "description": site["description"], "maintainer": {"@id": lab["id"]}})

    for pub in pubs:
        node = {"@type": "Thesis" if pub["kind"] == "thesis" else "ScholarlyArticle", "@id": BASE + "#" + pub["id"],
                "name": pub["title"],
                "author": [{"@id": person_id} if a == ME else {"@type": "Person", "name": a} for a in pub["authors"]],
                "datePublished": str(pub["year"])}
        url = primary_url(pub)
        if url:
            node["url"] = url
        if pub["kind"] == "thesis":
            node["inSupportOf"] = "Ph.D."
            school = pub["venue"].split(", ", 1)[-1]
            node["sourceOrganization"] = {"@type": "CollegeOrUniversity", "name": school}
        else:
            node["isPartOf"] = {"@type": "Periodical" if pub["kind"] == "journal" else "CreativeWork", "name": pub["venue"]}
        if pub["kind"] == "preprint":
            node["creativeWorkStatus"] = "Preprint"
        ids = []
        if pub.get("doi"):
            ids.append({"@type": "PropertyValue", "propertyID": "DOI", "value": pub["doi"]})
        if pub.get("arxiv"):
            ids.append({"@type": "PropertyValue", "propertyID": "arXiv", "value": pub["arxiv"]})
        if ids:
            node["identifier"] = ids if len(ids) > 1 else ids[0]
        same = [u for u in (("https://doi.org/" + pub["doi"]) if pub.get("doi") else None,
                            ("https://arxiv.org/abs/" + pub["arxiv"]) if pub.get("arxiv") else None) if u and u != url]
        if same:
            node["sameAs"] = same if len(same) > 1 else same[0]
        if pub.get("award"):
            node["award"] = pub["award"]
        graph.append(node)

    # One node per line: compact on the page, readable in diffs.
    text = '{"@context":"https://schema.org","@graph":[\n' + ",\n".join(
        json.dumps(n, ensure_ascii=False, separators=(",", ":")) for n in graph) + "\n]}"
    json.loads(text)
    text = text.replace("</", "<\\/")   # nothing can close the <script> element early
    return '<script type="application/ld+json">\n' + text + "\n</script>"


