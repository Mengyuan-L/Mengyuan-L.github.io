def replace_region(text, begin, end, content, name):
    start, stop = text.find(begin), text.find(end)
    if start < 0 or stop < start:
        raise SystemExit(f"index.html: markers for the {name} block are missing or out of order")
    return text[:start + len(begin)] + "\n" + content + "\n" + text[stop:]


def news_label(text):
    """Label the "Earlier news" disclosure with the years of the items it actually hides."""
    m = re.search(r'(<details class="more">\s*<summary>)(.*?)(</summary>)(.*?</details>)', text, re.S)
    if not m:
        return text
    years = sorted({int(y) for y in re.findall(r'datetime="(\d{4})', m.group(4))})
    if not years:
        return text
    label = f"Earlier news, {years[0]}–{years[-1]}" if years[0] != years[-1] else f"Earlier news, {years[0]}"
    return text[:m.start(2)] + label + text[m.end(2):]


def build_index(data, profile):
    text = INDEX.read_text(encoding="utf-8")
    text = replace_region(text, PUBS_BEGIN, PUBS_END, publications_html(data), "publications")
    text = replace_region(text, LD_BEGIN, LD_END, jsonld(profile, data["publications"], page_title(text)), "json-ld")
    return news_label(text)


