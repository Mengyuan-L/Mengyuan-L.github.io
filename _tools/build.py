def read_pages():
    pages = {}
    for path in sorted(ROOT.glob("*.html")):
        if path.name.startswith("google"):      # search-console verification file
            continue
        pages[path.name] = path.read_text(encoding="utf-8")
    return pages


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="write nothing; report stale outputs and site problems")
    args = ap.parse_args()

    data, profile = load_json(PUBS_JSON), load_json(PROFILE_JSON)
    pages = read_pages()
    outputs = OrderedDict()
    outputs[INDEX] = build_index(data, profile)
    pages["index.html"] = outputs[INDEX]
    outputs.update(bib_outputs(data["publications"]))
    outputs[LLMS_FULL] = export_text(pages)
    expected_bibs = {p for p in outputs if p.parent == BIB_DIR}
    orphans = sorted(p for p in BIB_DIR.glob("*.bib") if p not in expected_bibs) if BIB_DIR.exists() else []

    if args.check:
        problems = []
        for path, content in outputs.items():
            current = path.read_text(encoding="utf-8") if path.exists() else None
            if current != content:
                problems.append(f"{rel(path)} is stale: run python3 _tools/build.py")
        problems += [f"{rel(p)} has no publication record: run python3 _tools/build.py" for p in orphans]
        current_pages = read_pages()
        problems += site_problems(current_pages, data)
        for problem in problems:
            print("-", problem)
        print("OK" if not problems else f"{len(problems)} problem(s)")
        sys.exit(1 if problems else 0)

    written = 0
    for path, content in outputs.items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            written += 1
            print("wrote", rel(path))
    for path in orphans:
        path.unlink()
        print("removed", rel(path))
    print(f"{written} file(s) updated; {len(data['publications'])} publications, "
          f"{len(outputs) - 3} BibTeX files plus publications.bib, llms-full.txt from {len(PAGES)} pages")
    problems = site_problems(read_pages(), data)
    if problems:
        print(f"\n{len(problems)} site problem(s) (python3 _tools/build.py --check lists them and exits 1):")
        for problem in problems:
            print("-", problem)


if __name__ == "__main__":
    main()
