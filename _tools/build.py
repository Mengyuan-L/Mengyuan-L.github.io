def smart(text):
    """Typographic quotes for display: "x" -> “x”, ' -> ’."""
    out, open_quote = [], False
    for ch in text:
        if ch == '"':
            out.append("”" if open_quote else "“")
            open_quote = not open_quote
        elif ch == "'":
            out.append("’")
        else:
            out.append(ch)
    return "".join(out)


def esc(text):
    # Greek mu -> micro sign: the same glyph, but inside the Latin subset that assets/fonts/ serves, so
    # "μTESLA" stays in Literata instead of one character falling back to another font. Data, BibTeX and
    # JSON-LD keep the original.
    return html.escape(smart(text), quote=False).replace("μ", "µ")


def attr(text):
    return html.escape(text, quote=True)


def link(url, label):
    return f'<a href="{attr(url)}">{esc(label)}</a>'


def authors_html(pub, students=()):
    """Authors with the owner in bold. On the homepage list, names in `students` are bold too
    (topic pages call this without students, so only the owner is bold there)."""
    equal = set(pub.get("equal_contribution") or [])
    names = []
    for name in pub["authors"]:
        shown = esc(name).replace(" ", NBSP)          # a name never breaks across lines
        if name == ME or name in students:
            shown = f"<b>{shown}</b>"
        names.append(shown + ("*" if name in equal else ""))
    return ", ".join(names)


def venue_html(venue):
    """Escape the venue. A short parenthetical such as "(ACSAC 2021)" never splits across lines and stays
    with the word before it."""
    parts = re.split(r"( ?\([^()]{1,28}\))", venue)
    return "".join(esc(p).replace(" ", NBSP) if p.lstrip().startswith("(") else esc(p) for p in parts)


def acceptance_text(raw):
    m = re.match(r"\s*(\d+)\s*/\s*(\d+)\s*=\s*([\d.]+%)\s*$", raw)   # "57/407 = 14.0%"
    return f"Acceptance rate {m.group(3)} ({m.group(1)}/{m.group(2)})" if m else raw


def bib_path(pub):
    return (pub.get("bibtex") or {}).get("file") or f"files/bib/{pub['id']}.bib"


def primary_url(pub):
    """The best single link to the paper: DOI, else a Paper link, else arXiv, else the first link."""
    if pub.get("doi"):
        return "https://doi.org/" + pub["doi"]
    links = pub.get("links") or []
    for label in ("Paper", "arXiv"):
        for item in links:
            if item["label"] == label:
                return urljoin(BASE, item["url"])
    return urljoin(BASE, links[0]["url"]) if links else None


def tag_html(pub, show_year=False):
    if pub.get("kind") == "preprint":   # preprints sit in their own quiet group; the margin shows only the year
        return f'<span class="tag" data-export="skip">{pub["year"]}</span>'
    short = esc(pub.get("venue_short") or "")
    if show_year:   # entries in the "Before 2024" group have no year heading of their own
        short += f"&nbsp;{pub['year']}"
    label = TYPE_LABEL.get(pub.get("kind"))
    extra = f" <small>{label}</small>" if label and label.lower() not in (pub.get("venue_short") or "").lower() else ""
    # The tag repeats the venue line, so the text export skips it.
    return f'<span class="tag" data-export="skip">{short}{extra}</span>'


def disclosures_html(pub):
    """The .ds line ("Disclosures: AMD-SB-1023 · CVE-…"), or None."""
    disclosures = list(pub.get("disclosures") or []) + list(pub.get("extra_disclosures") or [])
    return "Disclosures: " + SEP.join(link(d["url"], d["label"]) for d in disclosures) if disclosures else None


def notes_html(pub):
    """One .nt line per note: its text, then its link."""
    lines = []
    for note in pub.get("notes") or []:
        text = esc(note["text"])
        if note.get("url"):
            text += " " + link(note["url"], note.get("label") or "Link")
        lines.append(text)
    return lines


def link_row(pub):
    """The .ln row: DOI, the record's links in order, BibTeX."""
    row = []
    if pub.get("doi"):
        row.append(link("https://doi.org/" + pub["doi"], "DOI"))
    row += [link(l["url"], l["label"]) for l in pub.get("links") or []]
    row.append(link(bib_path(pub), "BibTeX"))
    return SEP.join(row)


def entry_html(pub, show_year=False, students=()):
    cls = ' class="pre"' if pub.get("kind") == "preprint" else ""
    lines = [f'<li id="{attr(pub["id"])}"{cls}>{tag_html(pub, show_year)}',
             f"  <cite>{esc(pub['title'])}</cite>",
             f'  <span class="au">{authors_html(pub, students)}</span>']
    venue_text = pub["venue"]
    if pub.get("kind") == "preprint":   # under the "Preprints" heading, "arXiv:2610.25611" is enough
        venue_text = re.sub(r"^arXiv preprint\s+", "", venue_text)
    venue = f"<i>{venue_html(venue_text)}</i>"
    if (show_year or pub.get("kind") == "preprint") and str(pub["year"]) not in pub["venue"]:   # keep the year in the text export too
        venue += f", {pub['year']}"
    if pub.get("acceptance"):
        venue += SEP + f'<span class="ar">{esc(acceptance_text(pub["acceptance"]))}</span>'
    lines.append(f'  <span class="ve">{venue}</span>')
    if pub.get("award"):
        award = f"<strong>{esc(pub['award'])}</strong>"
        if pub.get("award_detail"):
            award += ", " + esc(pub["award_detail"])
        if pub.get("award_links"):
            award += " (" + ", ".join(link(l["url"], l["label"]) for l in pub["award_links"]) + ")"
        lines.append(f'  <span class="aw">{award}</span>')
    disclosures = disclosures_html(pub)
    if disclosures:
        lines.append(f'  <span class="ds">{disclosures}</span>')
    for note in notes_html(pub):
        lines.append(f'  <span class="nt">{note}</span>')
    lines.append(f'  <span class="ln">{link_row(pub)}</span></li>')
    return "\n".join(lines)


EARLIER = 2024   # papers published before this year share one "Before 2024" group


def by_year(pubs):
    """Published papers grouped by year, newest first (years before EARLIER share the key "earlier"),
    then all preprints in one final "preprints" group."""
    years = OrderedDict()
    published = [p for p in pubs if p.get("kind") != "preprint"]
    preprints = [p for p in pubs if p.get("kind") == "preprint"]
    for pub in sorted(published, key=lambda p: -p["year"]):   # stable: keeps the curated order within a year
        years.setdefault(pub["year"] if pub["year"] >= EARLIER else "earlier", []).append(pub)
    if preprints:
        years["preprints"] = sorted(preprints, key=lambda p: -p["year"])
    return years


def group_label(key):
    return {"earlier": f"Before {EARLIER}", "preprints": "Preprints"}.get(key, str(key))


def group_anchor(key):
    return {"earlier": f"pubs-before-{EARLIER}", "preprints": "pubs-preprints"}.get(key, f"pubs-{key}")


def publications_html(data):
    pubs = data["publications"]
    profiles = data.get("profiles") or {}
    years = by_year(pubs)
    index = SEP.join(f'<a href="#{group_anchor(y)}">{group_label(y)}</a>' for y in years)
    highlight = data.get("students") or {}
    students = set(highlight.get("names") or [])
    legend = (esc(highlight["note"]) + " ") if students and highlight.get("note") else ""
    legend += "* Equal contribution."
    if profiles.get("scholar"):
        legend += f' Also listed on <a href="{attr(profiles["scholar"])}">Google Scholar</a>.'
    parts = ['<div class="m pubhead"><span class="side">By year</span>',
             f'  <p class="years">{index}</p>',
             f"  <p>{legend}</p></div>"]
    for year, items in years.items():
        parts.append(f'<h3 class="yr" id="{group_anchor(year)}">{group_label(year)}</h3>\n<ol class="pubs" role="list">')
        parts.extend(entry_html(p, show_year=(year == "earlier"), students=students) for p in items)
        parts.append("</ol>")
    return "\n".join(parts)


