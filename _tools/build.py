LATEX_ACCENT = {"̀": "`", "́": "'", "̂": "^", "̃": "~", "̄": "=", "̆": "u",
                "̈": '"', "̊": "r", "̌": "v", "̧": "c"}
LATEX_CHAR = {"&": r"\&", "%": r"\%", "#": r"\#", "_": r"\_", "$": r"\$", "μ": r"{$\mu$}", "µ": r"{$\mu$}",
              "“": "``", "”": "''", "‘": "`", "’": "'", "–": "--", "—": "---", " ": "~"}


def tex(text):
    out, open_quote = [], False
    for ch in text:
        if ch == '"':
            out.append("''" if open_quote else "``")
            open_quote = not open_quote
        elif ch in LATEX_CHAR:
            out.append(LATEX_CHAR[ch])
        elif ord(ch) > 127:
            base, *marks = unicodedata.normalize("NFD", ch)
            accent = LATEX_ACCENT.get(marks[0]) if len(marks) == 1 else None
            if accent:
                out.append("{\\%s{%s}}" % (accent, base) if accent.isalpha() else "{\\%s%s}" % (accent, base))
            else:
                out.append(ch)
        else:
            out.append(ch)
    return "".join(out)


def protect(title):
    """Brace acronyms and camel-case words (TLB, SEV-SNP, vSGX, CatchBench, I/O) so styles keep their case."""
    out = []
    for token in re.split(r"(\s+)", title):
        core = token.strip(":,.;?!\"'()")
        if core and any(re.search(r"[A-Z].*[A-Z]|[a-z][A-Z]", part) for part in core.split("-")):
            token = token.replace(core, "{" + core + "}", 1)
        out.append(token)
    return "".join(out)


def bib_name(name):
    parts = name.split()
    return tex(parts[-1] + ", " + " ".join(parts[:-1]) if len(parts) > 1 else name)


def bib_entry(pub):
    bib = pub.get("bibtex") or {}
    kind = pub["kind"]
    fields = [("title", tex(protect(pub["title"]))), ("author", " and ".join(bib_name(a) for a in pub["authors"]))]
    if kind == "journal":
        etype = "article"
        fields.append(("journal", tex(bib.get("journal") or re.sub(r"\s*\([^()]*\)$", "", pub["venue"]))))
        fields += [(k, bib[k]) for k in ("volume", "number") if bib.get(k)]
    elif kind == "preprint":
        etype = "misc"
    elif kind == "thesis":
        etype = "phdthesis"
        fields.append(("school", tex(pub["venue"].split(", ", 1)[-1])))
    else:
        etype = "inproceedings"
        fields.append(("booktitle", tex(pub["venue"])))
    if bib.get("pages"):
        fields.append(("pages", bib["pages"]))
    fields.append(("year", str(pub["year"])))
    if pub.get("doi"):
        fields += [("doi", pub["doi"]), ("url", "https://doi.org/" + pub["doi"])]
    elif kind == "preprint" and pub.get("arxiv"):
        fields += [("eprint", pub["arxiv"]), ("archivePrefix", "arXiv"), ("url", "https://arxiv.org/abs/" + pub["arxiv"])]
    else:
        url = primary_url(pub)
        if url:
            fields.append(("url", url))
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields)
    return f"@{etype}{{{bib.get('key') or pub['id']},\n{body}\n}}\n"


def bib_outputs(pubs):
    outputs = OrderedDict()
    for pub in pubs:
        outputs[ROOT / bib_path(pub)] = bib_entry(pub)
    outputs[ALL_BIB] = ("% Publications of Mengyuan (Marvin) Li, University of Southern California\n"
                        "% Generated by _tools/build.py from _data/publications.json; list: " + BASE + "#publications\n\n"
                        + "\n".join(bib_entry(p) for p in pubs))
    return outputs


